// Rebuild the dark palette from the existing component styles: npm run build does not regenerate it.
import postcss from "postcss";
import { readFileSync, writeFileSync } from "node:fs";

const files = ["styles", "duration-tests", "mode-explanation", "performance-chart", "responses", "saved-inputs"];
const output = postcss.root();
const palette = (hex, property) => {
  const raw = hex.slice(1);
  if (![3, 4, 6, 8].includes(raw.length)) return hex;
  const full = raw.length <= 4 ? [...raw].map(c => c + c).join("") : raw;
  const channels = [0, 2, 4].map(i => parseInt(full.slice(i, i + 2), 16));
  const alpha = full.slice(6);
  const [r, g, b] = channels;
  const luminance = (r * 0.2126 + g * 0.7152 + b * 0.0722) / 255;
  const saturation = (Math.max(...channels) - Math.min(...channels)) / 255;
  let result;
  if (property === "color" || property === "fill") {
    if (luminance > .72) return hex;
    // Keep meaningful status hues, but lift them for contrast on dark surfaces.
    if (saturation > .22) result = channels.map(c => Math.round(c * .62 + 255 * .38));
    else result = luminance < .31 ? [218, 229, 237] : [173, 193, 207];
  } else {
    if (luminance < .62) return hex;
    if (property.startsWith("border") || property === "stroke") result = [59, 77, 90];
    else if (saturation > .10) result = channels.map(c => Math.round(c * .13));
    else result = luminance > .985 ? [29, 45, 57] : [24, 39, 50];
  }
  return "#" + result.map(c => c.toString(16).padStart(2, "0")).join("") + alpha;
};
for (const file of files) {
  const root = postcss.parse(readFileSync(`src/${file}.css`, "utf8"));
  root.walkRules(rule => {
    if (rule.parent?.type === "atrule" && !["media", "supports"].includes(rule.parent.name)) return;
    const declarations = [];
    rule.walkDecls(decl => {
      const prop = decl.prop.toLowerCase();
      if (!/^(color|background|background-color|border(?:-(?:top|right|bottom|left))?(?:-color)?|fill|stroke)$/.test(prop)) return;
      let value = decl.value.replace(/\bwhite\b/gi, "#ffffff").replace(/#[0-9a-fA-F]{3,8}\b/g, color => palette(color, prop));
      if (value !== decl.value) declarations.push(decl.clone({ value }));
    });
    if (!declarations.length) return;
    const selector = rule.selectors.map(s => s.includes(":root") ? s.replaceAll(":root", ":root[data-theme=dark]") : `:root[data-theme=dark] ${s}`).join(", ");
    const clone = postcss.rule({ selector });
    declarations.forEach(d => clone.append(d));
    if (rule.parent?.type === "atrule") {
      const wrapper = postcss.atRule({ name: rule.parent.name, params: rule.parent.params });
      wrapper.append(clone); output.append(wrapper);
    } else output.append(clone);
  });
}
writeFileSync("src/dark.css", `/* Generated by scripts/generate-dark-theme.mjs; component colors follow the dark palette. */\n${output.toString()}\n
:root[data-theme=dark] { color-scheme: dark; --ink: #dce7ee; --muted: #adbfcb; --line: #344b59; --focus: #8caaff; }
:root[data-theme=dark] .plot-surface { fill: #172731; }
:root[data-theme=dark] .segmented.mode-tabs button.active { border-color: #e59372; background: #49342f; color: #ffd0b9; }
`);
